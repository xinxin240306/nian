const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const androidDir = path.join(root, 'android');

function existsJava(home) {
  if (!home) return false;
  return fs.existsSync(path.join(home, 'bin', 'java.exe')) || fs.existsSync(path.join(home, 'bin', 'java'));
}

function javaMajor(home) {
  const exe = fs.existsSync(path.join(home, 'bin', 'java.exe'))
    ? path.join(home, 'bin', 'java.exe')
    : path.join(home, 'bin', 'java');
  const r = spawnSync(exe, ['-version'], { encoding: 'utf8' });
  const text = `${r.stderr || ''}\n${r.stdout || ''}`;
  const m = text.match(/version "(\d+)(?:\.(\d+))?/);
  if (!m) return 0;
  const major = Number(m[1]);
  return major === 1 ? Number(m[2] || 0) : major;
}

function findJdk17() {
  const homes = [
    path.join(root, '.tools', 'jdk-17'),
    process.env.JAVA_HOME,
    'D:\\IntelliJ IDEA 2024.1.4\\jbr',
    'C:\\Program Files\\Android\\Android Studio\\jbr',
    'C:\\Program Files\\Java\\jdk-17',
    'C:\\Program Files\\Eclipse Adoptium\\jdk-17',
    'C:\\Program Files\\Microsoft\\jdk-17',
  ].filter(Boolean);

  try {
    const pf = 'C:\\Program Files\\Java';
    if (fs.existsSync(pf)) {
      for (const name of fs.readdirSync(pf)) {
        if (/jdk-1[7-9]|jdk-2/i.test(name)) homes.push(path.join(pf, name));
      }
    }
  } catch {}

  for (const home of homes) {
    if (!existsJava(home)) continue;
    const major = javaMajor(home);
    if (major >= 17) return home;
    console.warn(`[android:debug] 跳过过旧 JDK ${home} (Java ${major || '?'})`);
  }
  return '';
}

function looksLikeSdk(dir) {
  if (!dir || !fs.existsSync(dir)) return false;
  return fs.existsSync(path.join(dir, 'platform-tools'))
    || fs.existsSync(path.join(dir, 'platforms'))
    || fs.existsSync(path.join(dir, 'build-tools'));
}

function findSdk() {
  const homes = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    path.join(root, '.tools', 'android-sdk'),
    'D:\\Android\\Sdk',
    'D:\\sdk',
    'C:\\Android\\Sdk',
    path.join(os.homedir(), 'AppData', 'Local', 'Android', 'Sdk'),
  ].filter(Boolean);
  for (const home of homes) {
    if (looksLikeSdk(home)) return home;
  }
  return '';
}

function writeLocalProperties(sdk) {
  const file = path.join(androidDir, 'local.properties');
  const escaped = sdk.replace(/\\/g, '\\\\').replace(/:/g, '\\:');
  fs.writeFileSync(file, `# Generated by scripts/android-debug.mjs — do not commit\nsdk.dir=${escaped}\n`);
  console.log('[android:debug] sdk.dir ->', sdk);
}

function run(cmd, args, extraEnv) {
  const r = spawnSync(cmd, args, {
    cwd: extraEnv.cwd || root,
    env: extraEnv.env,
    stdio: 'inherit',
    shell: true,
  });
  if (r.status !== 0) process.exit(r.status || 1);
}

function gradleDistHash(url) {
  const md5 = crypto.createHash('md5').update(url, 'utf8').digest();
  return BigInt(`0x${md5.toString('hex')}`).toString(36);
}

function realGradleUserHome() {
  return path.join(root, '.tools', 'gradle');
}

function seedGradleWrapperZip() {
  const zip = path.join(root, '.tools', 'gradle-8.2.1-all.zip');
  if (!fs.existsSync(zip) || fs.statSync(zip).size < 10_000_000) return false;
  const raw = fs.readFileSync(path.join(androidDir, 'gradle', 'wrapper', 'gradle-wrapper.properties'), 'utf8');
  const m = raw.match(/distributionUrl=(.+)/);
  if (!m) return false;
  const url = m[1].trim().replace(/\\:/g, ':');
  const destDir = path.join(realGradleUserHome(), 'wrapper', 'dists', 'gradle-8.2.1-all', gradleDistHash(url));
  fs.mkdirSync(destDir, { recursive: true });
  const destZip = path.join(destDir, 'gradle-8.2.1-all.zip');
  if (!fs.existsSync(destZip) || fs.statSync(destZip).size !== fs.statSync(zip).size) {
    try {
      if (fs.existsSync(destZip)) fs.unlinkSync(destZip);
      fs.linkSync(zip, destZip);
    } catch {
      fs.copyFileSync(zip, destZip);
    }
  }
  for (const name of fs.readdirSync(destDir)) {
    if (name.endsWith('.part') || name.endsWith('.lck')) {
      try { fs.unlinkSync(path.join(destDir, name)); } catch {}
    }
  }
  console.log('[android:debug] Gradle zip ->', destZip);
  return true;
}

function prepareGradleEnv(env) {
  const home = realGradleUserHome();
  fs.mkdirSync(home, { recursive: true });
  env.GRADLE_USER_HOME = home;
  for (const k of ['HTTP_PROXY', 'HTTPS_PROXY', 'http_proxy', 'https_proxy', 'ALL_PROXY', 'all_proxy']) {
    delete env[k];
  }
  const bypass = '-Djava.net.useSystemProxies=false';
  env.GRADLE_OPTS = `${env.GRADLE_OPTS || ''} ${bypass}`.trim();
  env.JAVA_OPTS = `${env.JAVA_OPTS || ''} ${bypass}`.trim();
  console.log('[android:debug] GRADLE_USER_HOME ->', home);
}

