function bumpVersion() {
  const file = path.join(androidDir, 'app', 'version.properties');
  let code = 1;
  if (fs.existsSync(file)) {
    const m = fs.readFileSync(file, 'utf8').match(/VERSION_CODE\s*=\s*(\d+)/);
    if (m) code = Number(m[1]);
  }
  code += 1;
  const name = `1.0.${code}`;
  fs.writeFileSync(file, `VERSION_CODE=${code}\nVERSION_NAME=${name}\n`);
  console.log(`[android:debug] versionCode -> ${code} (${name})`);
  return { code, name };
}

function publishUpdate(apkPath, ver) {
  const dir = path.join(root, 'backend', 'data', 'app-update');
  fs.mkdirSync(dir, { recursive: true });
  const dest = path.join(dir, 'nian.apk');
  fs.copyFileSync(apkPath, dest);
  const st = fs.statSync(dest);
  fs.writeFileSync(path.join(dir, 'version.json'), JSON.stringify({
    versionCode: ver.code,
    versionName: ver.name,
    size: st.size,
    builtAt: new Date().toISOString(),
  }, null, 2));
  console.log('[android:debug] 已挂到 backend/data/app-update ，手机连这个后端再进 App 会弹更新');
  console.log('[android:debug] 若后端在 VPS：把 backend/data/app-update 拷到服务器同路径即可，不用重启');
}

function tryAdbInstall(sdkHome, apkPath) {
  const adb = process.platform === 'win32'
    ? path.join(sdkHome, 'platform-tools', 'adb.exe')
    : path.join(sdkHome, 'platform-tools', 'adb');
  if (!fs.existsSync(adb)) return;
  const list = spawnSync(adb, ['devices'], { encoding: 'utf8' });
  const lines = `${list.stdout || ''}`.split(/\r?\n/).filter((l) => /\tdevice$/.test(l));
  if (!lines.length) {
    console.log('[android:debug] 没有已连接的 USB 调试设备，跳过 adb 安装');
    return;
  }
  console.log('[android:debug] 正在 adb 安装到手机…');
  const inst = spawnSync(adb, ['install', '-r', apkPath], { stdio: 'inherit', timeout: 180000 });
  if (inst.status === 0) console.log('[android:debug] adb 安装完成');
  else console.warn('[android:debug] adb 安装失败，可用应用内更新或手动装');
}
